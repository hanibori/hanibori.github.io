  function hasJong(s) {
    var t = String(s || '');
    for (var i = t.length - 1; i >= 0; i--) {
      var c = t.charCodeAt(i);
      if (c >= 0xAC00 && c <= 0xD7A3) return (c - 0xAC00) % 28 !== 0;
    }
    return false;
  }
